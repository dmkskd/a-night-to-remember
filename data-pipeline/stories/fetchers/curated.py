    print("Fetching curated world stories...")
    
    all_curated = []
    
    regions = [
        (LATIN_AMERICAN, "Latin American"),
        (JAPANESE, "Japanese"),
        (AFRICAN, "African"),
        (SOUTH_ASIAN, "South Asian"),
        (EASTERN_EUROPEAN, "Eastern European"),
    ]
    
    for story_list, region_name in regions:
        for item in story_list:
            all_curated.append({
                "title": item["title"],
                "author": item["author"],
                "year": item["year"],
                "country": item.get("country", ""),
                "collection": item.get("collection"),
                "genres": ["Literary Fiction", "World Literature"],
                "themes": item.get("themes", []),
                "recognitions": [{"type": f"{region_name} Essential", "year": item["year"], "details": "Curated"}],
            })
    
    print(f"  Found {len(all_curated)} curated stories")
    return all_curated
