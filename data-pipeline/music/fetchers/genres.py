def fetch_genre_essentials() -> list[dict]:
    """Return quality albums across all genres."""
    print("Fetching Genre Essentials...")
    albums = []
    
    # Map genres to their lists for proper tagging
    genre_map = [
        (COUNTRY_QUALITY, "Country Essential"),
        (RNB_QUALITY, "R&B Essential"),
        (REGGAE_QUALITY, "Reggae Essential"),
        (PUNK_QUALITY, "Punk Essential"),
        (BLUES_QUALITY, "Blues Essential"),
        (CLASSICAL_QUALITY, "Classical Essential"),
        (AMBIENT_QUALITY, "Ambient Essential"),
        (SHOEGAZE_QUALITY, "Shoegaze Essential"),
        (POSTROCK_QUALITY, "Post-Rock Essential"),
        (NOISE_QUALITY, "Noise Essential"),
        (LATIN_QUALITY, "Latin Essential"),
        (ASIAN_QUALITY, "Asian Essential"),
        (PROG_QUALITY, "Prog Essential"),
        (DOOM_QUALITY, "Doom Essential"),
        (BLACK_METAL_QUALITY, "Black Metal Essential"),
        (DEATH_METAL_QUALITY, "Death Metal Essential"),
    ]
    
    for genre_list, recognition_type in genre_map:
        for item in genre_list:
            albums.append({
                "artist": item["artist"],
                "title": item["album"],
                "year": item["year"],
                "recognitions": [{"type": recognition_type, "year": item["year"], "details": "Essential"}],
            })
    
    print(f"  Found {len(albums)} albums")
    return albums
