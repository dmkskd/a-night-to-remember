def fetch_curated_albums() -> list[dict]:
    """Return all curated quality albums from around the world."""
    print("Fetching curated world albums...")
    
    all_curated = []
    
    # Combine all regional lists
    regions = [
        (ECM_JAZZ, "ECM Jazz"),
        (NORDIC, "Nordic"),
        (TURKISH, "Turkish"),
        (ARGENTINA, "Argentine"),
        (BRAZIL, "Brazilian"),
        (JAPANESE_JAZZ, "Japanese Jazz"),
        (JAPANESE_MATH_ROCK, "Japanese Math Rock"),
        (JAPANESE_AMBIENT, "Japanese Ambient"),
        (KOREAN, "Korean"),
        (AFRICAN, "African"),
        (MIDDLE_EAST, "Middle East/South Asian"),
    ]
    
    for album_list, region_name in regions:
        for item in album_list:
            all_curated.append({
                "artist": item["artist"],
                "title": item["album"],
                "year": item["year"],
                "country": item.get("country", ""),
                "recognitions": [{"type": f"{region_name} Essential", "year": item["year"], "details": "Curated"}],
            })
    
    print(f"  Found {len(all_curated)} curated albums")
    return all_curated
